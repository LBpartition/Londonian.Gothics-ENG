"""Import edits from tools-resources\\EDIT and IMPORT - SCRIPT.txt back into tools-resources\\_import_script.json.

  python tools\\script_import.py [path\\to\\EDIT and IMPORT - SCRIPT.txt]

The doc is generated by script_dump.py in _import_script.json order, so entries are matched by
position. Dialogue: '---' = next text box (short boxes are padded with blank lines),
{word} = red highlight. Run full_build.py afterwards for the fit check."""
import json, re, sys
from pathlib import Path

W = Path(__file__).resolve().parents[1]
TR = W / "tools-resources"
DOC = Path(sys.argv[1]) if len(sys.argv) > 1 else TR / "EDIT and IMPORT - SCRIPT.txt"
SEP = "=" * 60
HL = lambda s: re.sub(r"\{([^{}]*)\}", r"{H}\1{/H}", s)


def sections(text):
    L = text.split("\n")
    out, k = {}, 0
    while k < len(L):
        if L[k] == SEP and k + 2 < len(L) and L[k + 2] == SEP:
            name, k = L[k + 1], k + 3
            body = []
            while k < len(L) and not (L[k] == SEP and k + 2 < len(L) and L[k + 2] == SEP):
                body.append(L[k]); k += 1
            out[name] = body
        else:
            k += 1
    return out


def blocks(body):
    """Split on blank lines -> list of line lists."""
    out, cur = [], []
    for l in body:
        if l.strip(): cur.append(l)
        elif cur: out.append(cur); cur = []
    return out + ([cur] if cur else [])


def pages(lines):
    """Indented dialogue lines with '---' markers -> flat in-game lines (pad short boxes)."""
    out, page = [], []
    for l in lines:
        if l.strip() == "---":
            out += page + [""] * (3 - len(page)); page = []
        else:
            page.append(HL(l.strip()))
    return out + page


def main():
    EN = json.load(open(TR / "_import_script.json", encoding="utf-8"))
    S = sections(DOC.read_text(encoding="utf-8"))
    changed = []

    def put(e, key, new, label):
        if e[key] != new:
            changed.append(f"{label}: {e[key]!r} -> {new!r}"); e[key] = new

    cr = [l.strip() for l in S["TITLE SCREEN CREDITS"] if l.strip() and not l.startswith("(<RC>")]
    if [e["en"] for e in EN["credits"]] != cr:
        changed.append(f"credits: {[e['en'] for e in EN['credits']]!r} -> {cr!r}")
        EN["credits"] = [{"en": t} for t in cr]

    intro = blocks(S["INTRO (PROLOGUE STORY ROLL)"])
    assert len(intro) == len(EN["intro"]), "intro block count changed"
    for e, b in zip(EN["intro"], intro):
        put(e, "en", [l.strip() for l in b], f"intro {e['block']}")

    for sec, key in (("DRESSES (DRESS MODE)", "dresses"), ("ITEMS", "items")):
        ents = [e for e in EN[key] if e["name"]]
        bs = blocks(S[sec])
        assert len(bs) == len(ents), f"{sec}: entry count changed"
        for e, b in zip(ents, bs):
            m = re.match(r"\d+\. (.*)", b[0]); assert m, b[0]
            put(e, "name", m.group(1).strip(), f"{key} {e['id']} name")
            d = [l.strip() for l in b[1:]]
            put(e, "desc", None if d == ["(no description)"] else d, f"{key} {e['id']} desc")

    seen = []
    for e in sorted(EN["locations"], key=lambda e: (not e["file"].startswith("sp_home"), e["file"])):
        if e["en"] not in seen: seen.append(e["en"])
    new = [l.strip() for l in S["LOCATION NAMES (top of map screen)"] if l.strip()]
    assert len(new) == len(seen), "location name count changed"
    ren = {a: b for a, b in zip(seen, new) if a != b}
    for e in EN["locations"]:
        if e["en"] in ren: put(e, "en", ren[e["en"]], f"location {e['file']}")

    menu = [l.strip() for l in S["MENU TEXT (OPTION screen)"] + S["MENU TEXT (SAVE / LOAD screens)"] + S["SYSTEM MESSAGES"] if l.strip()]
    assert len(menu) == len(EN["menu"]), "menu count changed"
    for e, t in zip(EN["menu"], menu):
        put(e, "en", t, f"menu {e['key']}")

    dl = [b for b in blocks(S["DIALOGUE"]) if not b[0].startswith("--- ")]
    assert len(dl) == len(EN["dialogue"]), f"dialogue count {len(dl)} != {len(EN['dialogue'])}"
    for e, b in zip(EN["dialogue"], dl):
        if "(untranslated" in b[0]: continue
        put(e, "en", pages(b[1:]), f"{e['file']}|{e['idx']}")

    (TR / "_import_script.json").write_text(json.dumps(EN, ensure_ascii=False, indent=1), encoding="utf-8")
    print(len(changed), "changes"); print("\n".join(changed))


if __name__ == "__main__":
    main()
